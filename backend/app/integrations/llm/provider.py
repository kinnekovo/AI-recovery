from app.core.config import get_settings


class LLMFeedbackProvider:
    provider_name = "base"

    def evaluate(self, target_text: str, transcript: str, task_type: str) -> dict:
        raise NotImplementedError


class MockLLMFeedbackProvider(LLMFeedbackProvider):
    provider_name = "mock"

    def __init__(self, requested_provider: str = "mock") -> None:
        self.requested_provider = requested_provider

    def evaluate(self, target_text: str, transcript: str, task_type: str) -> dict:
        return {
            "main_strength": "表达内容较完整",
            "main_issue": "音量略低",
            "suggestion": "下一次可以放慢一点，并把声音再提高一些。",
        }


def get_llm_feedback_provider() -> LLMFeedbackProvider:
    settings = get_settings()
    # Real providers must only return natural-language feedback fields. Scores,
    # metric values, and clinical facts are generated by deterministic services.
    return MockLLMFeedbackProvider(requested_provider=settings.llm_feedback_provider)


def get_llm_scoring_provider() -> LLMFeedbackProvider:
    return get_llm_feedback_provider()
